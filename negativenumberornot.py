"""
This module is to check if a number is negative or not using if-else condition statement.
"""

number = float(input("Enter a number: "))
if number < 0:
    print(f"{number} is a negative number.")
else:
    print(f"{number} is not a negative number.")
print("Congrats you have implemented the if-else condition statement to check if a number is negative or not.")
