"""
This program is demonstrate the use of math module.
"""

import math

num = int(input("Enter a number: "))
# finding square root of a number using math module.
print(f"Square root of {num} is: {math.sqrt(num)}")
# finding natural logarithm of a number using math module.
print(f"Natural logarithm of {num} is: {math.log(num)}")
# finding sine of a number using math module in radians.
print(f"Sine of {num} is: {math.sin(num)}")
